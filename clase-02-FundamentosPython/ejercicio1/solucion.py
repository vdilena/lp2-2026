numero_uno = int(input("Primer numero: "))
segundo_numero = int(input("Segundo numero: "))

print(f"Suma: {numero_uno + segundo_numero}")
print("Resta: " + str(numero_uno - segundo_numero))
print(f"Multiplicacion:  {numero_uno * segundo_numero}")
print(f"Division: {numero_uno / segundo_numero}")
print(f"Potencia: {numero_uno ** segundo_numero}")
print(f"Resto: {numero_uno % segundo_numero}")
